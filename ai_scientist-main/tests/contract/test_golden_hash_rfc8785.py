@pytest.mark.parametrize("value,expected", GOLDEN_VECTORS)
def test_rfc8785_golden_vectors(value, expected: bytes) -> None:
    assert canonical_json.canonicalize(value) == expected


@pytest.mark.parametrize("binary64_hex,expected", APPENDIX_B_NUMBER_VECTORS)
def test_rfc8785_appendix_b_number_vectors(binary64_hex: str, expected: bytes) -> None:
    value = struct.unpack(">d", bytes.fromhex(binary64_hex))[0]
    assert canonical_json.canonicalize(value) == expected


def test_nan_and_infinity_are_rejected() -> None:
    for bad in (float("nan"), float("inf"), float("-inf")):
        with pytest.raises(ValueError):
            canonical_json.canonicalize(bad)


def test_non_binary64_safe_integer_collision_is_rejected() -> None:
    safe = 9_007_199_254_740_992
    unsafe = 9_007_199_254_740_993
    assert canonical_json.canonicalize(safe) == b"9007199254740992"
    with pytest.raises(ValueError, match="not exactly representable"):
        canonical_json.canonicalize(unsafe)
    with pytest.raises(ValueError, match="not exactly representable"):
        canonical_json.content_hash({"nested": [unsafe]})


def test_non_json_inputs_have_stable_failures() -> None:
    with pytest.raises(TypeError, match="keys must be strings"):
        canonical_json.canonicalize({1: "not an object key"})
    with pytest.raises(TypeError, match="not a JSON-compatible type"):
        canonical_json.canonicalize((1, 2))
    with pytest.raises(ValueError, match="lone UTF-16 surrogate"):
        canonical_json.canonicalize("\ud800")

    cyclic: list[object] = []
    cyclic.append(cyclic)
    with pytest.raises(ValueError, match="cyclic containers"):
        canonical_json.canonicalize(cyclic)


def test_identity_critical_jcs_dependency_is_exactly_pinned() -> None:
    pyproject = (ROOT / "pyproject.toml").read_text(encoding="utf-8")
    assert '"jcs==0.2.1"' in pyproject


def _load(relative: str) -> dict:
    return json.loads((ROOT / relative).read_text(encoding="utf-8"))


def test_reproduces_locked_baseline_content_hash() -> None:
    lock = _load("governance/baseline.lock.json")
    assert canonical_json.content_hash_excluding(lock) == lock["content_hash"]


def test_reproduces_locked_decision_record_content_hashes() -> None:
    lock = _load("governance/baseline.lock.json")
    for record in lock["decision_records"]:
        obj = _load(record["ref"])
        assert canonical_json.content_hash_excluding(obj) == record["content_hash"], record["ref"]


def test_reproduces_locked_research_question_and_workflow_hashes() -> None:
    lock = _load("governance/baseline.lock.json")
    research_question = _load(lock["research_question"]["ref"])
    assert (
        canonical_json.content_hash_excluding(research_question)
        == lock["research_question"]["content_hash"]
    )
    workflow = _load(lock["workflow"]["ref"])
    assert canonical_json.content_hash_excluding(workflow) == lock["workflow"]["content_hash"]


def test_content_hash_excluding_removes_only_own_field() -> None:
    obj = {"a": 1, "content_hash": "x"}
    assert canonical_json.content_hash_excluding(obj) == canonical_json.content_hash({"a": 1})
