"""RFC 8785 canonical JSON: official fixed Golden vectors + baseline regression.

Every expected canonical byte string below is a pre-fixed constant taken from
the RFC 8785 / ECMAScript ``Number::toString`` rules — never generated by the
implementation under test. The baseline regression is the second, independent
source of truth: T000's locked ``content_hash`` values were produced by the
project owner's toolchain, and must be reproduced exactly.
"""
from __future__ import annotations

import json
import struct
from pathlib import Path

import pytest

from ai_scientist_mvp.domain import canonical_json

ROOT = Path(__file__).resolve().parents[2]


# Fixed RFC 8785 canonical bytes: (python value, expected canonical UTF-8).
GOLDEN_VECTORS = [
    # numbers: ECMAScript Number::toString / JSON.stringify semantics
    (0.5, b"0.5"),
    (1e21, b"1e+21"),
    (1e-6, b"0.000001"),
    (1e-7, b"1e-7"),
    (-0.0, b"0"),
    (1.5, b"1.5"),
    (-1.25, b"-1.25"),
    (2.5e-3, b"0.0025"),
    # object key ordering (UTF-16 code units)
    ({"b": 1, "a": 2}, b'{"a":2,"b":1}'),
    # minimal string escaping (control characters)
    ("a\nb\tc", b'"a\\nb\\tc"'),
    # non-ASCII kept raw as UTF-8
    ({"k": "中"}, b'{"k":"\xe4\xb8\xad"}'),
    # UTF-16 key ordering places astral (U+1F600) before BMP U+E000,
    # unlike Unicode code-point order.
    ({chr(0x1F600): 1, chr(0xE000): 2}, b'{"\xf0\x9f\x98\x80":1,"\xee\x80\x80":2}'),
]

